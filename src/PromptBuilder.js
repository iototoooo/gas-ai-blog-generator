/**
 * PromptBuilder.js
 * Claude に渡すプロンプトと、出力形式（JSON Schema）を組み立てる。
 */

/** Claude の出力形式。structured outputs で強制し、コード側でも検証する */
var ARTICLE_SCHEMA = {
  type: 'object',
  properties: {
    title: { type: 'string', description: '記事タイトル（32文字前後、メインキーワードを含む）' },
    meta_description: { type: 'string', description: 'メタディスクリプション（120文字以内）' },
    introduction: { type: 'string', description: '導入文' },
    sections: {
      type: 'array',
      description: 'H2見出しと本文のセット。必ず3つ',
      items: {
        type: 'object',
        properties: {
          heading: { type: 'string', description: 'H2見出し' },
          body: { type: 'string', description: '見出し配下の本文' }
        },
        required: ['heading', 'body'],
        additionalProperties: false
      }
    },
    summary: { type: 'string', description: 'まとめ本文' }
  },
  required: ['title', 'meta_description', 'introduction', 'sections', 'summary'],
  additionalProperties: false
};

/**
 * システムプロンプトを返す。settings.promptVersion で版を選ぶ（既定 v2）。
 * @param {Object} [settings] getSettings_() の戻り値
 */
function buildSystemPrompt_(settings) {
  var version = settings && settings.promptVersion ? settings.promptVersion : DEFAULT_PROMPT_VERSION;
  return version === 'v1' ? buildSystemPromptV1_() : buildSystemPromptV2_();
}

