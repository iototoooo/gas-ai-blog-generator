/**
 * @param {Object} params
 * @param {string} params.keyword メインキーワード
 * @param {string} params.subKeywords サブキーワード（カンマ・読点・改行区切り）
 * @param {string} params.sampleText 文体参考用のサンプル記事
 * @param {string[]} params.feedback 前回出力の問題点（再試行時）
 * @param {{name:string, category:string, facts:string}} [params.service] 紹介するサービス（v2のみ）
 */
function buildUserPrompt_(params) {
  var subs = splitSubKeywords_(params.subKeywords);
  var lines = [];
  lines.push('次の条件でブログ記事を1本作成してください。');
  lines.push('');
  lines.push('<keyword>' + params.keyword + '</keyword>');
  if (subs.length > 0) {
    lines.push('<sub_keywords>' + subs.join('、') + '</sub_keywords>');
    lines.push('サブキーワードは見出しや本文に自然な形で取り入れてください（無理に全部を詰め込まない）。');
  }
  if (params.sampleText) {
    lines.push('');
    lines.push('以下は文体の参考用サンプル記事です。文章は流用せず、語り口だけを参考にしてください。');
    lines.push('<sample_article>');
    lines.push(params.sampleText);
    lines.push('</sample_article>');
  }
  if (params.service && params.service.name) {
    lines.push('');
    lines.push('記事の内容と関連がある場合だけ、次のサービスを控えめに紹介してください。');
    lines.push('<service>');
    lines.push('<service_name>' + params.service.name + '</service_name>');
    if (params.service.category) lines.push('<service_category>' + params.service.category + '</service_category>');
    if (params.service.facts) {
      lines.push('<service_facts>');
      lines.push(params.service.facts);
      lines.push('</service_facts>');
    } else {
      lines.push('（機能・料金・実績の情報は提供されていません。サービス名とカテゴリ以外は書かないでください）');
    }
    lines.push('</service>');
  }
  if (params.feedback && params.feedback.length > 0) {
    lines.push('');
    lines.push('前回の出力には次の問題がありました。必ず修正したうえで、記事全体を書き直してください。');
    params.feedback.forEach(function (f) { lines.push('- ' + f); });
  }
  return lines.join('\n');
}

function splitSubKeywords_(text) {
  return String(text || '')
    .split(/[,、，\n]/)
    .map(function (s) { return s.trim(); })
    .filter(function (s) { return s !== ''; });
}
